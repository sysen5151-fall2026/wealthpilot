def build_response(directory, database, investor=None):
    client = TestClient(create_app(Planner(snapshot_directory=directory, database_path=database)))
    session_id = client.post("/api/sessions").json()["session_id"]
    response = client.post(f"/api/sessions/{session_id}/investor-information", json=investor or SAMPLE_INVESTOR)
    assert response.status_code == 200, response.text
    response = client.post(f"/api/sessions/{session_id}/plan", json={"profile_interpretation_confirmed": True})
    assert response.status_code == 200, response.text
    return response.json()


def seed_case(directory, name, base, minimum):
    rows = copy.deepcopy(base)
    if name == "missing-symbol":
        rows = [r for r in rows if r["symbol"] != "AAPL"]
    elif name == "blank-symbol":
        for row in rows:
            if row["symbol"] == "AAPL": row["symbol"] = ""
    elif name == "duplicate-date":
        rows.append(copy.deepcopy(next(r for r in rows if r["symbol"] == "AAPL")))
    elif name == "short-history":
        kept = [r for r in rows if r["symbol"] == "AAPL"][:minimum-1]
        rows = [r for r in rows if r["symbol"] != "AAPL"] + kept
    elif name == "disjoint-interval":
        for row in rows:
            if row["symbol"] == "VXUS":
                row["date"] = (date.fromisoformat(row["date"]) - timedelta(days=4000)).isoformat()
    elif name.startswith("date-") or name.startswith("price-"):
        bad = next(r for r in rows if r["symbol"] == "AAPL")
        values = {"date-empty": "", "date-null": None, "date-invalid": "2026-02-30",
                  "date-compact": "20261030", "date-timestamp": "2026-10-30T00:00:00",
                  "price-empty": "", "price-null": None, "price-text": "unknown", "price-zero": "0",
                  "price-negative": "-1", "price-nan": "NaN", "price-inf": "inf", "price-minus-inf": "-inf"}
        bad["date" if name.startswith("date-") else "adjusted_close"] = values[name]
    elif name == "valid-unsorted":
        rows.reverse()
    manifest = write_snapshot_files(directory, rows)
    path = directory / manifest["file"]
    if name.startswith("missing-column-"):
        field = name.removeprefix("missing-column-")
        fields = [f for f in ("symbol", "date", "adjusted_close") if f != field]
        with path.open("w", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
            writer.writeheader(); writer.writerows(rows)
        manifest["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    if name == "non-utf8":
        path.write_bytes(b"\xff\xfe\x80")
        manifest["sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
    if name == "fingerprint-mismatch": path.write_text(path.read_text()+"\n")
    if name == "missing-data-file": path.unlink()
    if name == "manifest-null-file": manifest["file"] = None
    (directory / "manifest.json").write_text(json.dumps(manifest))
    if name == "manifest-array": (directory / "manifest.json").write_text("[]")
    if name == "manifest-invalid-json": (directory / "manifest.json").write_text("{broken")
    if name == "missing-manifest": (directory / "manifest.json").unlink()


N05_CASES = ["valid", "valid-unsorted", "missing-symbol", "blank-symbol", "duplicate-date", "short-history",
    "date-empty", "date-null", "date-invalid", "date-compact", "date-timestamp",
    "price-empty", "price-null", "price-text", "price-zero", "price-negative", "price-nan", "price-inf", "price-minus-inf",
    "missing-column-symbol", "missing-column-date", "missing-column-adjusted_close", "non-utf8",
    "fingerprint-mismatch", "missing-data-file", "manifest-null-file", "manifest-array", "manifest-invalid-json",
    "missing-manifest", "disjoint-interval"]


def audit_n05(work):
    config = load_configuration()
    minimum = config.security_screening_criteria["min_observations"]
    base = synthetic_rows()
    symbols = list(config.security_screening_criteria["instruments"])
    records = []
    for name in N05_CASES:
        directory = work / name
        seed_case(directory, name, base, minimum)
        data = provide_historical_market_data(MarketDataRequest(symbols), snapshot_directory=directory, minimum_observations=minimum)
        for symbol, series in data.series.items():
            assert symbol and len(series.dates) >= minimum, name
            assert len(series.dates) == len(series.adjusted_closes) == len(set(series.dates)), name
            assert series.dates == sorted(series.dates), name
            assert all(re.fullmatch(r"\d{4}-\d{2}-\d{2}", d) and date.fromisoformat(d) for d in series.dates), name
            assert all(math.isfinite(p) and p > 0 for p in series.adjusted_closes), name
        body = build_response(directory, work / f"{name}.db")
        if name in ("valid", "valid-unsorted"):
            assert set(data.series) == set(symbols) and not data.limitations, name
            assert body["status"] == "presented", name
        elif name == "disjoint-interval":
            assert body["status"] == "withheld" and "common" in body["reason"], name
            assert body["limitations"] and "presented_plan" not in body, name
        elif name.startswith(("missing-column-", "manifest-")) or name in (
            "non-utf8", "fingerprint-mismatch", "missing-data-file", "missing-manifest"):
            assert not data.series and data.limitations, name
            assert body["status"] == "withheld" and body["limitations"] and "presented_plan" not in body, name
        else:
            assert "AAPL" not in data.series and data.limitations, name
            assert body["status"] == "presented", name
            content = body["presented_plan"]["content"]
            assert "AAPL" not in [r["symbol"] for r in content["recommendations"]], name
            assert set(data.limitations) <= set(content["explanation"]["data_limitations"]), name
            assert all(lim in body["presented_plan"]["display_text"] for lim in data.limitations), name
        records.append({"case": name, "checks_passed": True, "admitted_symbols": list(data.series),
                        "plan_status": body["status"], "limitations": body.get("limitations", data.limitations)})
    return {"need": "N-05", "scope": "fixed synthetic contract cases and HTTP/display-payload disclosure; not a user study",
            "configuration_id": config.configuration_id, "minimum_observations": minimum,
            "cases": records, "passed": len(records), "total": len(N05_CASES)}


def n01_profiles():
    cases = []
    goals = ["retirement", "home_purchase", "education", "general_wealth"]
    for i in range(10):
        investor = copy.deepcopy(SAMPLE_INVESTOR)
        investor["financial_profile"].update(goal=goals[i % 4], horizon_years=[1,3,5,8,10,15,20,25,30,40][i],
            investable_savings=1000+3000*i, monthly_contribution=50*i, annual_income=30000+7000*i,
            liquidity_needs=["low","medium","high"][i % 3])
        investor["current_holdings"] = ([] if i == 0 else [{"symbol": "VTI", "value": 1000*i}, {"symbol": "BND", "value": 200*i}])
        cases.append((f"N01-{i+1:02d}", investor))
    return cases


def prepare_n01(work):
    directory = work / "n01-prices"
    write_snapshot_files(directory, synthetic_rows())
    records = []
    for case_id, investor in n01_profiles():
        body = build_response(directory, work / f"{case_id}.db", investor)
        assert body["status"] == "presented", case_id
        plan = body["presented_plan"]
        profile, content = investor["financial_profile"], plan["content"]
        basis, amounts = content["profile_basis"], content["simulated_amounts"]
        checks = {
            "goal": basis["goal"] == profile["goal"],
            "horizon": basis["horizon_years"] == profile["horizon_years"],
            "financial_capacity": all(basis[k] == profile[k] for k in ("investable_savings", "monthly_contribution", "annual_income"))
                and amounts["cash"] == profile["investable_savings"],
            "holdings": basis["current_holdings"] == investor["current_holdings"]
                and amounts["current_holdings_value"] == sum(h["value"] for h in investor["current_holdings"]),
        }
        assert all(checks.values()), (case_id, checks)
        records.append({"case_id": case_id, "synthetic_input": investor, "automated_consistency_checks": checks,
                        "plan_id": plan["plan_id"], "display_text": plan["display_text"],
                        "independent_review": {"reviewer_id": None, "date": None, "independence_confirmed": None,
                                               "all_four_inputs_consistent": None, "notes": ""}})
    return {"need": "N-01", "status": "READY_FOR_INDEPENDENT_REVIEW_NOT_ACCEPTED",
            "automated_cases_passed": len(records), "acceptance_requires": "Independent review: at least 9 of 10 profiles consistent in all four inputs.", "cases": records}


def validate_n01_review(packet):
    cases = packet["cases"]
    assert len(cases) == 10 and len({c["case_id"] for c in cases}) == 10, "Review all ten distinct cases"
    for c in cases:
        review = c["independent_review"]
        assert isinstance(review["reviewer_id"], str) and review["reviewer_id"].strip(), "Record the real reviewer ID"
        assert review["independence_confirmed"] is True, "Reviewer must confirm independence from the author"
        date.fromisoformat(review["date"])
        assert type(review["all_four_inputs_consistent"]) is bool, "Record a true or false review decision"
        assert isinstance(review["notes"], str) and review["notes"].strip(), "Record the basis for the decision"
    assert sum(c["independent_review"]["all_four_inputs_consistent"] for c in cases) >= 9, "N-01 needs at least 9/10 independent passes"


